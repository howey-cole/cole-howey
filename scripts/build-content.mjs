// Reads content/*.md and bot/system-prompt.md, then writes:
//   public/content.json  -> the pages the website shows
//   lib/knowledge.js     -> the same text, for the chatbot
// One copy of the content feeds both. Files with "status: draft" are skipped.
// Run with: npm run build

import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return name.endsWith('.md') ? [full] : [];
  });
}

function parseFile(path) {
  const raw = readFileSync(path, 'utf8')
    .replace(/^﻿/, '')
    .replace(/\r\n/g, '\n')
    .replace(/<!--[\s\S]*?-->/g, ''); // comments never reach the site or the bot
  const match = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!match) throw new Error(`Missing frontmatter in ${path}`);
  const meta = {};
  for (const line of match[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  for (const key of ['title', 'section']) {
    if (!meta[key]) throw new Error(`Missing "${key}" in ${path}`);
  }
  return { meta, body: raw.slice(match[0].length).trim(), slug: basename(path, '.md') };
}

const escapeHtml = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const inline = (s) =>
  escapeHtml(s)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+|#\/[^\s)]*)\)/g, '<a href="$2">$1</a>');

// A small markdown-to-HTML converter: headings, bullet lists, paragraphs, bold, links.
function toHtml(markdown) {
  const out = [];
  let paragraph = [];
  let inList = false;
  const flushParagraph = () => {
    if (paragraph.length) out.push(`<p>${inline(paragraph.join(' '))}</p>`);
    paragraph = [];
  };
  const closeList = () => {
    if (inList) out.push('</ul>');
    inList = false;
  };
  for (const line of markdown.split('\n')) {
    const heading = line.match(/^(#{1,3})\s+(.*)$/);
    const bullet = line.match(/^\s*-\s+(.*)$/);
    if (heading) {
      flushParagraph();
      closeList();
      const level = heading[1].length;
      out.push(`<h${level}>${inline(heading[2])}</h${level}>`);
    } else if (bullet) {
      flushParagraph();
      if (!inList) out.push('<ul>');
      inList = true;
      out.push(`<li>${inline(bullet[1])}</li>`);
    } else if (line.trim() === '') {
      flushParagraph();
      closeList();
    } else {
      closeList();
      paragraph.push(line.trim());
    }
  }
  flushParagraph();
  closeList();
  return out.join('\n');
}

const pages = walk(join(root, 'content'))
  .map(parseFile)
  .filter((p) => p.meta.status === 'published')
  .sort((a, b) => Number(a.meta.order || 99) - Number(b.meta.order || 99));

const site = pages.map((p) => ({
  section: p.meta.section,
  slug: p.slug,
  title: p.meta.title,
  html: toHtml(p.body),
}));

const knowledge = pages
  .map((p) => `===== ${p.meta.section.toUpperCase()}: ${p.meta.title} =====\n${p.body}`)
  .join('\n\n');

const rules = readFileSync(join(root, 'bot', 'system-prompt.md'), 'utf8').replace(/\r\n/g, '\n').trim();

mkdirSync(join(root, 'public'), { recursive: true });
mkdirSync(join(root, 'lib'), { recursive: true });
writeFileSync(join(root, 'public', 'content.json'), JSON.stringify({ pages: site }, null, 1));
writeFileSync(
  join(root, 'lib', 'knowledge.js'),
  '// GENERATED by scripts/build-content.mjs. Do not edit; edit content/ and bot/ instead.\n' +
    `export const RULES = ${JSON.stringify(rules)};\n` +
    `export const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`
);

console.log(`Built ${pages.length} published pages (${knowledge.length.toLocaleString()} characters of knowledge).`);
